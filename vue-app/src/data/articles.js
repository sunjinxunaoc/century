export const MIN_TAG_ARTICLES = 2

export function tagSlug(name) {
  return String(name).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')
}

export const tagList = (() => {
  const map = new Map()
  for (const a of articles) {
    for (const t of a.tags || []) {
      const slug = tagSlug(t)
      if (!map.has(slug)) map.set(slug, { name: t, slug, articles: [] })
      map.get(slug).articles.push(a)
    }
  }
  return [...map.values()].sort((x, y) => y.articles.length - x.articles.length || x.name.localeCompare(y.name))
})()

export const hubTags = tagList.filter(t => t.articles.length >= MIN_TAG_ARTICLES)

export function tagBySlug(slug) {
  return tagList.find(t => t.slug === slug) || null
}
