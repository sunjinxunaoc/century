export function findCategory(slug) {
  return categories.find(c => c.slug === slug)
}

export function findSubcategory(categorySlug, subSlug) {
  const cat = findCategory(categorySlug)
  if (!cat) return null
  return cat.subcategories.find(s => s.slug === subSlug) || null
}

export function findProduct(categorySlug, productSlug) {
  const cat = findCategory(categorySlug)
  if (!cat) return null
  for (const sub of cat.subcategories) {
    const p = (sub.products || []).find(x => x.slug === productSlug)
    if (p) return { product: p, subcategory: sub }
  }
  return null
}

export function relatedProducts(categorySlug, currentSlug, count = 3) {
  const cat = findCategory(categorySlug)
  if (!cat) return []
  const all = []
  for (const sub of cat.subcategories) {
    for (const p of (sub.products || [])) {
      if (p.slug !== currentSlug) all.push({ ...p, subSlug: sub.slug })
    }
  }
  return all.slice(0, count)
}
